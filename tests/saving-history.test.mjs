import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { createContext, runInContext } from 'node:vm';
const context = createContext({ structuredClone });
for (const name of ['engine','base-generation','project','history','project-files']) runInContext(await readFile(new URL('../app/src/' + name + '.js', import.meta.url), 'utf8'), context);
const { PaintHistory, PaintProjectFiles, PaintProject } = context;
const images = { final: { name: 'large image', data: 'large immutable image source' } };
const project = { images, name: 'A', stages: [{ points: [{ x: .1 }] }] };
const history = PaintHistory.create(3); history.reset(project, { selected: 0 });
project.name = 'B'; history.commit(project, {}, 'name');
project.name = 'C'; history.commit(project, {}, 'name');
assert.equal(history.peek(-1).project.name, 'A', 'Typing must coalesce');
assert.equal(history.peek(-1).project.images, images, 'History must share large image data');
history.endGroup(); history.markSaved();
project.name = 'D'; history.commit(project, {});
assert.equal(history.clean, false); history.move(-1); assert.equal(history.clean, true);
project.name = 'Other branch'; history.commit(project, {}); assert.equal(history.canRedo, false);
for (let i = 0; i < 10; i++) { project.name = String(i); history.commit(project, {}); }
let steps = 0; while (history.canUndo) { history.move(-1); steps++; } assert.equal(steps, 3);
history.reset(project, {}); assert.equal(history.canUndo, false); assert.equal(history.clean, true);
assert.equal(PaintProject.filename('Historia del windsurf'), 'historia-del-windsurf.colorflow.json');
assert.equal(PaintProject.filename('../CON'), 'proyecto-con.colorflow.json');
assert.equal(PaintProject.normalizeName(' A\nB '), 'AB');
let picks = 0, writes = [], fail = false, cancel = false, handles = 0, aborts = 0;
const picker = async () => {
  picks++; if (cancel) throw Object.assign(new Error('cancel'), { name: 'AbortError' });
  const name = 'selected-' + (++handles) + '.colorflow.json';
  return { name, async createWritable() { return { async write(text) { if (fail) throw new Error('disk full'); writes.push({ name, text }); }, async close() {}, async abort() { aborts++; } }; } };
};
const files = PaintProjectFiles.create({ picker: () => picker, download() { throw new Error('Must not silently download on failure'); } });
await files.save(project, { suggestedName: 'first.colorflow.json', description: 'project' });
await files.save(project, { suggestedName: 'second.colorflow.json' }); assert.equal(picks, 1, 'Save must reuse authorized handle');
fail = true; await assert.rejects(files.save(project, { saveAs: true }), /disk full/); assert.equal(aborts, 1);
fail = false; await files.save(project, {}); assert.equal(writes.at(-1).name, 'selected-1.colorflow.json', 'Failed Save As must retain previous target');
cancel = true; await assert.rejects(files.save(project, { saveAs: true }), e => e.name === 'AbortError');
cancel = false; files.reset(); await files.save(project, {}); assert.equal(picks, 4, 'Opening another project must release previous target');
let download;
const fallback = PaintProjectFiles.create({ picker: () => null, download(...args) { download = args; } });
await fallback.save(project, { suggestedName: 'recommended.colorflow.json' });
assert.equal(download[0], 'recommended.colorflow.json'); assert.equal(JSON.parse(download[1]).name, project.name);
console.log('History grouping, saved-state tracking, branches, limits, shared images, file permissions, failed/canceled saves and download fallback verified.');
