import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { createContext, runInContext } from 'node:vm';
const context = createContext({}); runInContext(await readFile(new URL('../app/src/canvas-viewport.js', import.meta.url), 'utf8'), context);
const model = context.PaintCanvasViewport.createModel(), close = (a, b) => assert.ok(Math.abs(a - b) < 1e-8, `${a} != ${b}`);
model.resize(600, 400, 20); model.source(1000, 800); close(model.state().scale, .45);
model.preset('width'); close(model.state().width, 560);
model.preset('height'); close(model.state().height, 360);
model.preset('1'); close(model.state().width, 1000); close(model.state().height, 800);
const anchor = { x: 350, y: 230 }, before = model.state(), px = (anchor.x - before.left) / before.width, py = (anchor.y - before.top) / before.height;
model.zoom(2, anchor.x, anchor.y); const after = model.state();
close((anchor.x - after.left) / after.width, px); close((anchor.y - after.top) / after.height, py);
model.pan(70, 40); close(model.state().left, after.left + 70); close(model.state().top, after.top + 40);
model.resize(800, 500); close(model.state().scale, 2);
model.preset('fit'); model.resize(500, 350); close(model.state().scale, 310 / 800);
model.pan(1e6, -1e6); close(model.state().cx, .5); close(model.state().cy, .5);
model.preset('width'); model.resize(800, 600); close(model.state().width, 760);
model.zoom(100); close(model.state().scale, 8); model.zoom(.0001); close(model.state().scale, .05);
model.reset(); assert.equal(model.state().available, false); model.source(1000, 800); assert.equal(model.state().mode, 'fit');
console.log('Viewport presets, cursor anchor, panning, bounds, resize modes and reset verified.');
